"""Render rytm-mods-src's symbol map (re/symbols.toml) as an assembler include.

    python3 tools/gen_symbols.py ../rytm-mods-src/re/symbols.toml include/ar2-1.73.inc

Every main-OS function, data and constant entry becomes an absolute `.equ`.
Absolute symbols are plain numbers to the elemod linker: they need no
relocation and are never exported, so every mod can include the same file.
Entries for the bootstrap image or for hardware registers are left out, as
rytm-mods-src's own tools/symbols.py leaves them out. Only addresses and
constants are written: no firmware bytes.
"""
import sys
import tomllib

KINDS = ("fn", "data", "const")
EXPECTED_MAIN_SHA256 = "28d9ef40c895e03f17dfce096543109adaf708947392db72818fc2a412d685d6"


def main(src, dst):
    with open(src, "rb") as fh:
        syms = tomllib.load(fh)
    meta = syms["meta"]
    if meta.get("mainos_sha256") != EXPECTED_MAIN_SHA256:
        sys.exit("symbols.toml is not for Analog Rytm MKII OS 1.73's main OS")
    table = {}
    for kind in KINDS:
        for name, entry in syms.get(kind, {}).items():
            if entry.get("image", "mainos") != "mainos":
                continue
            value = entry["value"] if kind == "const" else entry["addr"]
            if name in table:
                sys.exit("duplicate symbol %r" % name)
            table[name] = (value, kind, entry.get("status", "unknown"))
    lines = [
        "| Generated by tools/gen_symbols.py from rytm-mods-src re/symbols.toml - do not edit.",
        "| Analog Rytm MKII OS 1.73, main OS sha256 %s" % EXPECTED_MAIN_SHA256,
        "| Addresses and constants only.",
        "",
    ]
    for name, (value, kind, status) in sorted(table.items(), key=lambda kv: (kv[1][0], kv[0])):
        lines.append("        .equ    %s, 0x%08x   | %s, %s" % (name, value, kind, status))
    with open(dst, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("%s: %d symbols" % (dst, len(table)))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
